USE DATABASE P2P_ANALYTICS;
USE WAREHOUSE P2P_WH;
-- All source values land as strings; parsing failures remain inspectable.
-- RAW is append-only by convention and by the loader grant (no UPDATE/DELETE).

CREATE TABLE IF NOT EXISTS RAW.SUPPLIERS (
    SUPPLIER_ID VARCHAR,
    SUPPLIER_NAME VARCHAR,
    CATEGORY VARCHAR,
    COUNTRY VARCHAR,
    PAYMENT_TERMS_DAYS VARCHAR,
    EFFECTIVE_FROM VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW.PURCHASE_ORDERS (
    PO_ID VARCHAR,
    SUPPLIER_ID VARCHAR,
    ORDER_DATE VARCHAR,
    STATUS VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW.PO_LINES (
    PO_LINE_ID VARCHAR,
    PO_ID VARCHAR,
    LINE_NUMBER VARCHAR,
    DESCRIPTION VARCHAR,
    QUANTITY VARCHAR,
    UNIT_PRICE_CENTS VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW.INVOICES (
    INVOICE_ID VARCHAR,
    SUPPLIER_ID VARCHAR,
    INVOICE_DATE VARCHAR,
    DUE_DATE VARCHAR,
    INVOICE_NUMBER VARCHAR,
    INVOICE_TOTAL_CENTS VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW.INVOICE_LINES (
    INVOICE_LINE_ID VARCHAR,
    INVOICE_ID VARCHAR,
    LINE_NUMBER VARCHAR,
    PO_LINE_ID VARCHAR,
    DESCRIPTION VARCHAR,
    QUANTITY VARCHAR,
    UNIT_PRICE_CENTS VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW.PAYMENTS (
    PAYMENT_ID VARCHAR,
    INVOICE_ID VARCHAR,
    PAYMENT_DATE VARCHAR,
    AMOUNT_CENTS VARCHAR,
    SOURCE_UPDATED_AT VARCHAR,
    BATCH_ID VARCHAR,
    SOURCE_FILENAME VARCHAR NOT NULL,
    SOURCE_FILE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    SOURCE_FILE_CONTENT_KEY VARCHAR,
    INGESTED_AT TIMESTAMP_LTZ NOT NULL
);
