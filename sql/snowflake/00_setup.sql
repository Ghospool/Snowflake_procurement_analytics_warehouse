-- Deployment only. Run as an administrator permitted to create these objects.
-- Existing objects are preserved; IF NOT EXISTS is not a schema migration.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS P2P_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
-- Reassert settings on replay without recreating the warehouse.
ALTER WAREHOUSE P2P_WH SET WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    STATEMENT_TIMEOUT_IN_SECONDS = 300 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 60;
CREATE DATABASE IF NOT EXISTS P2P_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS P2P_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS P2P_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS P2P_ANALYTICS.MART;
USE DATABASE P2P_ANALYTICS;
USE WAREHOUSE P2P_WH;
CREATE FILE FORMAT IF NOT EXISTS RAW.P2P_CSV
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('')
    EMPTY_FIELD_AS_NULL = TRUE TRIM_SPACE = FALSE ESCAPE_UNENCLOSED_FIELD = NONE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE ENCODING = 'UTF8';
CREATE STAGE IF NOT EXISTS RAW.P2P_STAGE FILE_FORMAT = RAW.P2P_CSV;
